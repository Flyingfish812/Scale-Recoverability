# LaTeX tables
# ══════════════════════════════════════════════════════════════════════
def fmt(v: float, n: int = 4) -> str:
    return f"{float(v):.{n}f}"


def table_analytical_benchmark(cons: dict) -> str:
    cases = cons["p0_1"]["cases"]
    lines = [TAB_HEADER,
             r"\begin{tabular}{lcccccc}",
             r"  \toprule",
             r"  Case & $\Sfull^{\mathrm{exp}}$ & \GER{} & $\Sfull$ & $\Scoh$ & Corr. \\",
             r"  \midrule"]
    for c in CASES:
        d = cases[c]
        scoh = f"{d['S_coh_mean']:.1f}" if d.get("S_coh_mean") is not None else "---"
        lines.append(
            f"  {CASE_LABEL[c]} & {d['expected_S_full']} & {fmt(d['GER_mean'])} "
            f"& {fmt(d['S_full_mean'], 1)} & {scoh} & {fmt(d['S_full_correct_frac'], 2)} \\\\"
        )
    lines += [r"  \bottomrule", r"\end{tabular}"]
    lines += ["", r"\medskip", "", TAB_HEADER,
              r"\begin{tabular}{lcccccc}",
              r"  \toprule",
              r"  Case & A4 & W4 & W3 & W2 & W1 \\",
              r"  \midrule"]
    fracs = cons["p0_1"]["target_band_energy_fractions"]
    for c in CASES:
        d = cases[c]
        lines.append("  " + CASE_LABEL[c] + " & "
                     + " & ".join(fmt(d["E_direct_mean"][b]) for b in BANDS_CF) + r" \\")
    lines.append(r"  \midrule")
    lines.append(r"  Target $\omega_b$ & " + " & ".join(fmt(fracs[b], 3) for b in BANDS_CF) + r" \\")
    lines += [r"  \bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def table_wavelet_sensitivity(cons: dict) -> str:
    nc = cons["p0_2"]["real_nc"]
    lines = [TAB_HEADER,
             r"\begin{tabular}{llcccccccc}",
             r"  \toprule",
             r"  Wavelet & Model & \makecell{$\Sfull$\\mode} & \makecell{$\Scoh$\\mode} & \GER{}"
             r" & A4 & W4 & W3 & W2 & W1 \\",
             r"  \midrule"]
    for wt in WAVELETS:
        for m in MODELS:
            d = nc[wt][m]
            errs = " & ".join(fmt(d["E_direct_mean"][b], 3) for b in BANDS_CF)
            lines.append(f"  {wt} & {MODEL_LABEL[m]} & {d['S_full_mode']} & {d['S_coh_mode']} "
                         f"& {fmt(d['GER_mean'])} & {errs} \\\\")
        if wt != WAVELETS[-1]:
            lines.append(r"  \addlinespace")
    lines += [r"  \bottomrule", r"\end{tabular}"]
    # analytical benchmark detection block
    det = cons["p0_2"]["analytical_benchmark_detection"]
    lines += ["", r"\medskip", "", TAB_HEADER,
              r"\begin{tabular}{lcccccc}",
              r"  \toprule",
              r"  Wavelet & \makecell{analytical case A\\correct} & B & C & D & E1 & E2 \\",
              r"  \midrule"]
    for wt in WAVELETS:
        row = f"  {wt} & " + " & ".join(f"{det[wt][c]:.2f}" for c in CASES) + r" \\"
        lines.append(row)
    lines += [r"  \bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


