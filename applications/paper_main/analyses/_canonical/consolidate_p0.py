def update_registry() -> None:
    if not REGISTRY.exists():
        print(f"[warn] registry missing: {REGISTRY}")
        return
    lines = REGISTRY.read_text(encoding="utf-8").splitlines()
    header = lines[0]
    ids = {r[0] for r in REGISTRY_ROWS} | {"tab_wavelet_sensitivity.tex"}  # 旧名行弃用
    kept = [ln for ln in lines[1:] if ln.strip() and ln.split(",")[0] not in ids]
    with open(REGISTRY, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(header.split(","))
        for ln in kept:
            w.writerow(ln.split(","))
        for r in REGISTRY_ROWS:
            w.writerow(r)
    print(f"[registry] refreshed {len(REGISTRY_ROWS)} P0 entries (stale rows replaced)")


