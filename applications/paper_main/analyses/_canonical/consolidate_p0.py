# ══════════════════════════════════════════════════════════════════════
def main() -> int:
    P0_DIR.mkdir(parents=True, exist_ok=True)
    TABLES_DIR.mkdir(parents=True, exist_ok=True)

    ab, ws = load()
    cons = build_consolidated(ab, ws)

    # JSON
    (P0_DIR / "p0_consolidated.json").write_text(
        json.dumps(cons, indent=2, default=float), encoding="utf-8")

    # CSV (flat)
    csv_path = P0_DIR / "p0_consolidated.csv"
    with open(csv_path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["domain", "wavelet_or_case", "model", "GER_mean", "S_full_mean",
                    "S_full_mode", "S_full_correct", "S_coh_mean"] + [f"E_{b}" for b in BANDS_CF])
        for c in CASES:
            d = cons["p0_1"]["cases"][c]
            w.writerow(["analytical_benchmark", c, "-", round(d["GER_mean"], 4),
                        round(d["S_full_mean"], 2), d["expected_S_full"],
                        round(d["S_full_correct_frac"], 3),
                        round(d["S_coh_mean"], 2) if d["S_coh_mean"] else "NA"]
                       + [round(d["E_direct_mean"][b], 4) for b in BANDS_CF])
        for wt in WAVELETS:
            for m in MODELS:
                d = cons["p0_2"]["real_nc"][wt][m]
                w.writerow(["wavelet_sensitivity", wt, m, round(d["GER_mean"], 4),
                            round(d["S_full_mean"], 2), d["S_full_mode"], "NA",
                            d["S_coh_mode"]]
                           + [round(d["E_direct_mean"][b], 4) for b in BANDS_CF])

    # YAML facts
    (P0_DIR / "p0_facts.yaml").write_text(build_facts_yaml(cons), encoding="utf-8")

    # LaTeX tables
    (TABLES_DIR / "tab_analytical_benchmark.tex").write_text(
        table_analytical_benchmark(cons), encoding="utf-8")
    (TABLES_DIR / "tab_wavelet_family_sensitivity.tex").write_text(
        table_wavelet_sensitivity(cons), encoding="utf-8")

    # README (flat: name-prefixed to avoid clobbering build/data/
    (P0_DIR / "p0_patch_README.md").write_text(README, encoding="utf-8")

    # Registry
    update_registry()

    # console summary
    print("=" * 78)
    print("  P0 CONSOLIDATION — package written")
    print("=" * 78)
    for p in sorted(P0_DIR.glob("p0_*")):
        print(f"  [data ] {p.relative_to(_PROJECT_ROOT)}")
    for t in ["tab_analytical_benchmark.tex", "tab_wavelet_family_sensitivity.tex"]:
        print(f"  [table] { (TABLES_DIR / t).relative_to(_PROJECT_ROOT) }")
    print("  [figs ] build/figures/fig_analytical_benchmark.{pdf,png}")
    print("          build/figures/fig_wavelet_sensitivity.{pdf,png}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
